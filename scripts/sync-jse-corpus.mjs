// Copies javascript-excel's conformance corpus (JSE-9) into this repository,
// so react-data-export's conformance tests run the same workbooks through its
// public API (packages/react-data-export/test/conformance/).
//
// The corpus is not part of the javascript-excel npm package, so it is taken
// from the git tag of the installed version: the files always describe the
// engine the tests run against.
//
//   node scripts/sync-jse-corpus.mjs           write the files for the installed version
//   node scripts/sync-jse-corpus.mjs --check   fail if they differ from that version's files
//
// Only Node built-ins (fetch needs network access to raw.githubusercontent.com).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const out = join(root, 'packages/react-data-export/test/conformance/jse');
const check = process.argv.includes('--check');

const require = createRequire(join(root, 'packages/react-data-export/package.json'));
const { version } = JSON.parse(readFileSync(require.resolve('javascript-excel/package.json'), 'utf8'));
const tag = `v${version}`;
const base = `https://raw.githubusercontent.com/securedeveloper/javascript-excel/${tag}/packages/javascript-excel/test`;

const FILES = [
  {
    from: 'conformance/corpus.ts',
    to: 'corpus.ts',
    // The corpus imports the engine's sources; here it uses the installed package.
    transform: (text) => {
      const replaced = text.replace(/from "\.\.\/\.\.\/src\/index";/g, 'from "javascript-excel";');
      if (replaced === text) throw new Error('corpus.ts: the import of ../../src/index was not found; update this script');
      return `// Generated by scripts/sync-jse-corpus.mjs from javascript-excel ${tag}\n// (packages/javascript-excel/test/conformance/corpus.ts). Do not edit.\n${replaced}`;
    },
  },
  {
    from: 'interop/xlsx_dump.py',
    to: 'xlsx_dump.py',
    transform: (text) => `# Generated by scripts/sync-jse-corpus.mjs from javascript-excel ${tag}\n# (packages/javascript-excel/test/interop/xlsx_dump.py). Do not edit.\n${text}`,
  },
];

let stale = 0;
for (const f of FILES) {
  const res = await fetch(`${base}/${f.from}`);
  if (!res.ok) throw new Error(`${base}/${f.from}: HTTP ${res.status}`);
  const want = f.transform(await res.text());
  const path = join(out, f.to);
  let have;
  try {
    have = readFileSync(path, 'utf8');
  } catch {
    have = undefined;
  }
  if (have === want) continue;
  if (check) {
    stale++;
    console.error(`${f.to} differs from javascript-excel ${tag}`);
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${f.to} (javascript-excel ${tag})`);
  }
}
if (stale) {
  console.error(`run: npm run conformance:sync`);
  process.exit(1);
}
if (check) console.log(`ok the conformance corpus matches javascript-excel ${tag}`);
